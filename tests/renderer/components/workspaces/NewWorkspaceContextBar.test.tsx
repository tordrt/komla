/**
 * @vitest-environment jsdom
 */
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import React, { useRef, useState } from 'react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  NewWorkspaceContextBar,
  NewWorkspaceProjectPicker,
} from '../../../../src/renderer/components/workspaces/NewWorkspaceContextBar';
import { seedShortcuts } from '../../../helpers/shortcuts';

import type { NewWorkspaceMenu } from '../../../../src/renderer/lib/agent-dialog-shortcuts';
import type { Project } from '../../../../src/shared/types';

vi.mock('../../../../src/renderer/components/workspaces/WorkspaceBranchPicker', () => ({
  WorkspaceBranchPicker: () => null,
}));

const projects = Array.from({ length: 11 }, (_, index) => ({
  id: `project-${index + 1}`,
  name: `Project ${['one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven'][index]}`,
  color: '#888',
  repositoryPath: `/repos/${index + 1}`,
})) as Project[];

function ContextBar({
  initialPickerOpen = false,
  initialProjectId = projects[0].id,
  onSelectProject,
  onSetUpSshHost = vi.fn(),
}: {
  initialPickerOpen?: boolean;
  initialProjectId?: string;
  onSelectProject?: (id: string) => void;
  onSetUpSshHost?: () => void;
}) {
  const promptTextareaRef = useRef<HTMLTextAreaElement>(null);
  const branchInputRef = useRef<HTMLInputElement>(null);
  const projectTriggerRef = useRef<HTMLButtonElement>(null);
  const [projectId, setProjectId] = useState(initialProjectId);
  const [projectPickerOpen, setProjectPickerOpen] = useState(initialPickerOpen);
  const [openMenu, setOpenMenu] = useState<NewWorkspaceMenu | null>(null);
  const selectedProject = projects.find((project) => project.id === projectId);

  return (
    // Opens the project search like the dialog's New workspace shortcut.
    <div
      onKeyDown={(event) => {
        if (event.ctrlKey && event.key === 'n') setProjectPickerOpen(true);
      }}
    >
      <NewWorkspaceProjectPicker
        projects={projects}
        projectId={projectId}
        setProjectId={(id) => {
          onSelectProject?.(id);
          setProjectId(id);
        }}
        selectedProject={selectedProject}
        projectPickerOpen={projectPickerOpen}
        onProjectPickerOpenChange={setProjectPickerOpen}
        onAddProject={vi.fn()}
        onOpenFolderWorkspace={vi.fn()}
        flash={false}
        projectTriggerRef={projectTriggerRef}
        promptTextareaRef={promptTextareaRef}
        branchInputRef={branchInputRef}
      />
      <textarea aria-label="Prompt" ref={promptTextareaRef} />
      <NewWorkspaceContextBar
        selectedProject={selectedProject}
        environment={{
          launchTarget: 'local',
          onEnvironmentChange: vi.fn(),
          sshHosts: [],
          selectedSshHost: undefined,
          onSetUpSshHost,
        }}
        openMenu={openMenu}
        onMenuOpenChange={(menu, open) => setOpenMenu(open ? menu : null)}
        repoPath="/repos/1"
        baseBranch=""
        baseBranchLabel="main"
        setBaseBranch={vi.fn()}
        existingBranch=""
        openExistingBranch={vi.fn()}
        clearExistingBranch={vi.fn()}
        usedBranches={[]}
        findWorkspaceForBranch={() => undefined}
        onGoToWorkspace={vi.fn()}
        branchName="swift-fox"
        setBranchName={vi.fn()}
        setIsBranchNameAutoGenerated={vi.fn()}
        useAiBranchName={false}
        setUseAiBranchName={vi.fn()}
        toggleAiBranchName={vi.fn()}
        showAiToggle={false}
        initialPromptText=""
        branchInputRef={branchInputRef}
        promptTextareaRef={promptTextareaRef}
        projectTriggerRef={projectTriggerRef}
        openMenu={openMenu}
        onMenuOpenChange={(menu, open) => setOpenMenu(open ? menu : null)}
      />
    </div>
  );
}

const getOptions = () => within(screen.getByRole('listbox')).getAllByRole('option');
// Lets a menu's close-autofocus timer run.
const nextTick = () => new Promise((resolve) => setTimeout(resolve, 20));

describe('NewWorkspaceContextBar', () => {
  const OriginalResizeObserver = globalThis.ResizeObserver;
  const originalScrollIntoView = Element.prototype.scrollIntoView;
  const originalApi = (window as unknown as { api: unknown }).api;

  beforeEach(() => {
    (window as unknown as { api: unknown }).api = { platform: 'linux' };
    seedShortcuts();
    globalThis.ResizeObserver = class {
      observe() {}
      unobserve() {}
      disconnect() {}
    } as unknown as typeof ResizeObserver;
    Element.prototype.scrollIntoView = vi.fn();
  });

  afterEach(() => {
    globalThis.ResizeObserver = OriginalResizeObserver;
    Element.prototype.scrollIntoView = originalScrollIntoView;
    (window as unknown as { api: unknown }).api = originalApi;
  });

  it('shows the 1–9 shortcut of each project in the project dropdown', async () => {
    const user = userEvent.setup();
    render(<ContextBar />);

    await user.click(screen.getByRole('button', { name: /Project one/ }));

    const items = await screen.findAllByRole('menuitem', { name: /^Project / });
    expect(items).toHaveLength(11);
    expect(items[0]).toHaveTextContent(/Project one\s*Ctrl\+1$/);
    expect(items[8]).toHaveTextContent(/Project nine\s*Ctrl\+9$/);
    expect(items[9]).not.toHaveTextContent(/Ctrl/);
  });

  it('offers the project search in the project dropdown with the New workspace keys', async () => {
    const user = userEvent.setup();
    render(<ContextBar />);
    const trigger = screen.getByRole('button', { name: /Project one/ });
    expect(trigger).toHaveAttribute('title', 'Choose project, Ctrl+N searches');

    await user.click(trigger);
    const search = await screen.findByRole('menuitem', { name: /Search projects/ });
    expect(search).toHaveTextContent(/Search projects…\s*Ctrl\+N$/);
    await user.click(search);
    await nextTick();

    expect(await screen.findByRole('combobox', { name: 'Search projects' })).toHaveFocus();
    expect(screen.queryByRole('menuitem', { name: /Search projects/ })).not.toBeInTheDocument();
  });

  it('keeps the project search open when opened from the open project dropdown', async () => {
    const user = userEvent.setup();
    render(<ContextBar />);
    await user.click(screen.getByRole('button', { name: /Project one/ }));
    await screen.findAllByRole('menuitem', { name: /^Project / });

    await user.keyboard('{Control>}n{/Control}');

    const search = await screen.findByRole('combobox', { name: /search projects/i });
    await waitFor(() => expect(screen.queryByRole('menu')).not.toBeInTheDocument());
    // The closing dropdown returns focus on a timer; it must not take it from the search.
    await nextTick();
    expect(search).toBeInTheDocument();
    expect(search).toHaveFocus();
  });

  it('focuses the project search, with each project number shown', async () => {
    render(<ContextBar initialPickerOpen />);

    const search = await screen.findByRole('combobox', { name: /search projects/i });
    await waitFor(() => expect(search).toHaveFocus());
    const options = getOptions();
    expect(options).toHaveLength(11);
    expect(options[0]).toHaveAttribute('aria-selected', 'true');
    expect(options[1]).toHaveTextContent(/Project two\s*Ctrl\+2$/);
    expect(options[10]).not.toHaveTextContent(/Ctrl/);
  });

  it('opens scrolled to the current project', async () => {
    render(<ContextBar initialPickerOpen initialProjectId="project-11" />);

    await screen.findByRole('combobox', { name: /search projects/i });
    const options = getOptions();
    expect(options[10]).toHaveAttribute('aria-selected', 'true');
    expect(vi.mocked(Element.prototype.scrollIntoView).mock.contexts).toContain(options[10]);
  });

  it('moves the selection with the arrow keys and picks it with Enter', async () => {
    const user = userEvent.setup();
    const onSelectProject = vi.fn();
    render(<ContextBar initialPickerOpen onSelectProject={onSelectProject} />);
    const search = await screen.findByRole('combobox', { name: /search projects/i });
    await waitFor(() => expect(search).toHaveFocus());

    await user.keyboard('{ArrowDown}{ArrowDown}{ArrowUp}');
    expect(getOptions()[1]).toHaveAttribute('aria-selected', 'true');
    expect(search).toHaveAttribute('aria-activedescendant', getOptions()[1].id);
    await user.keyboard('{Enter}');

    expect(onSelectProject).toHaveBeenCalledWith('project-2');
    await waitFor(() => expect(screen.queryByRole('combobox')).not.toBeInTheDocument());
    await waitFor(() => expect(screen.getByRole('textbox', { name: 'Prompt' })).toHaveFocus());
  });

  it('filters by name to reach projects past the ninth', async () => {
    const user = userEvent.setup();
    const onSelectProject = vi.fn();
    render(<ContextBar initialPickerOpen onSelectProject={onSelectProject} />);
    const search = await screen.findByRole('combobox', { name: /search projects/i });
    await waitFor(() => expect(search).toHaveFocus());

    await user.type(search, 'ELEV');
    expect(getOptions()).toHaveLength(1);
    expect(getOptions()[0]).toHaveTextContent('Project eleven');
    expect(getOptions()[0]).toHaveAttribute('aria-selected', 'true');
    await user.keyboard('{Enter}');

    expect(onSelectProject).toHaveBeenCalledWith('project-11');
  });

  it('says when no project matches', async () => {
    const user = userEvent.setup();
    const onSelectProject = vi.fn();
    render(<ContextBar initialPickerOpen onSelectProject={onSelectProject} />);
    const search = await screen.findByRole('combobox', { name: /search projects/i });
    await waitFor(() => expect(search).toHaveFocus());

    await user.type(search, 'nothing like this');
    expect(screen.getByText('No matching projects')).toBeInTheDocument();
    await user.keyboard('{Enter}');

    expect(onSelectProject).not.toHaveBeenCalled();
    expect(search).toBeInTheDocument();
  });

  it('ignores Enter while an input method is composing', async () => {
    const onSelectProject = vi.fn();
    render(<ContextBar initialPickerOpen onSelectProject={onSelectProject} />);
    const search = await screen.findByRole('combobox', { name: /search projects/i });

    fireEvent.keyDown(search, { key: 'Enter', isComposing: true });

    expect(onSelectProject).not.toHaveBeenCalled();
    expect(search).toBeInTheDocument();
  });

  it('follows the pointer but not rows that scroll under it', async () => {
    render(<ContextBar initialPickerOpen />);
    await screen.findByRole('combobox', { name: /search projects/i });

    // Keyboard scrolling slides rows under a resting pointer, which fires mouseenter.
    fireEvent.mouseEnter(getOptions()[3]);
    expect(getOptions()[0]).toHaveAttribute('aria-selected', 'true');

    fireEvent.pointerMove(getOptions()[3]);
    expect(getOptions()[3]).toHaveAttribute('aria-selected', 'true');
  });

  it('picks a project with the mouse', async () => {
    const user = userEvent.setup();
    const onSelectProject = vi.fn();
    render(<ContextBar initialPickerOpen onSelectProject={onSelectProject} />);

    await user.click(await screen.findByRole('option', { name: /Project three/ }));

    expect(onSelectProject).toHaveBeenCalledWith('project-3');
    await waitFor(() => expect(screen.queryByRole('combobox')).not.toBeInTheDocument());
  });

  it('closes the project search on Escape and refocuses the prompt', async () => {
    const user = userEvent.setup();
    const onSelectProject = vi.fn();
    render(<ContextBar initialPickerOpen onSelectProject={onSelectProject} />);
    const search = await screen.findByRole('combobox', { name: /search projects/i });
    await waitFor(() => expect(search).toHaveFocus());

    await user.keyboard('{Escape}');

    await waitFor(() => expect(screen.queryByRole('combobox')).not.toBeInTheDocument());
    await waitFor(() => expect(screen.getByRole('textbox', { name: 'Prompt' })).toHaveFocus());
    expect(onSelectProject).not.toHaveBeenCalled();
  });

  it('returns focus to the prompt when a menu is closed with its own button', async () => {
    const user = userEvent.setup();
    render(<ContextBar />);
    const projectButton = screen.getByRole('button', { name: /Project one/ });
    await user.click(projectButton);
    await screen.findAllByRole('menuitem', { name: /^Project / });

    await user.click(projectButton);

    await waitFor(() => expect(screen.queryByRole('menu')).not.toBeInTheDocument());
    await nextTick();
    expect(screen.getByRole('textbox', { name: 'Prompt' })).toHaveFocus();
  });

  it('leaves focus on the control clicked to close the project search', async () => {
    const user = userEvent.setup();
    render(<ContextBar initialPickerOpen />);
    const search = await screen.findByRole('combobox', { name: /search projects/i });
    await waitFor(() => expect(search).toHaveFocus());

    const branchInput = screen.getByRole('textbox', { name: 'Branch name' });
    await user.click(branchInput);

    await waitFor(() => expect(screen.queryByRole('combobox')).not.toBeInTheDocument());
    await nextTick();
    expect(branchInput).toHaveFocus();
  });

  it('offers SSH setup, not a sandbox, while Local is the only environment', async () => {
    const user = userEvent.setup();
    const onSetUpSshHost = vi.fn();
    render(<ContextBar onSetUpSshHost={onSetUpSshHost} />);

    await user.click(screen.getByRole('button', { name: 'Local' }));

    expect(screen.getAllByRole('menuitem').map((item) => item.textContent)).toEqual([
      'Local',
      'Connect a machine over SSH…',
    ]);
    await user.click(screen.getByRole('menuitem', { name: 'Connect a machine over SSH…' }));
    expect(onSetUpSshHost).toHaveBeenCalledOnce();
  });
});
