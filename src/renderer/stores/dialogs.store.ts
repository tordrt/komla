import { create } from 'zustand';

import type { LaunchTarget, WorkspaceEnvironmentTarget } from '@/lib/agent-launch';
import type { Workspace } from '@/types';

/** The new-workspace dialog's choices at Launch, so undoing the launch can bring them back. */
export interface NewWorkspaceDialogDraft {
  prompt: string;
  attachments: string[];
  projectId: string;
  branchMode: 'new' | 'existing';
  branchName: string;
  isBranchNameAutoGenerated: boolean;
  existingBranch: string;
  existingBranchIsRemote: boolean;
  baseBranch: string;
  /** The SSH host whose clone the base or opened branch came from ('' = origin or this computer) */
  branchHostId: string;
  launchTarget: WorkspaceEnvironmentTarget | undefined;
  sshHostId: string;
  actionId: string;
  presetId: string | null;
  launchModeId: string | null;
  reasoningLevelOverrides: Record<string, string | null>;
  launchTargets: LaunchTarget[];
  aiBranchNameOverride: boolean | null;
  sourceWorkspaceId: string;
}

export interface NewWorkspaceDialogPrefill {
  baseBranch?: string;
  projectId?: string;
  actionId?: string;
  sshHostId?: string;
  sourceWorkspaceId?: string;
  /** Opens the add-project form on this folder. */
  addProjectPath?: string;
  /** Agents to start with, in order; several launch one workspace each where the dialog allows. */
  presetIds?: string[];
  /** Called with the agents a launch started, which can be fewer than `presetIds`. */
  onLaunch?: (presetIds: string[]) => void;
  /** Restores every choice of an undone launch; the other fields are ignored. */
  draft?: NewWorkspaceDialogDraft;
}

interface DialogsState {
  // New Workspace Dialog
  newWorkspaceDialogPrompt: string;
  /** Files attached to the prompt when the dialog last closed */
  newWorkspaceDialogAttachments: string[];
  newWorkspaceDialogPrefill: NewWorkspaceDialogPrefill | null;
  pendingWorkspacePrompts: Record<string, string>;

  // Actions
  setNewWorkspaceDialogPrompt: (prompt: string) => void;
  setNewWorkspaceDialogAttachments: (attachments: string[]) => void;
  clearNewWorkspaceDialogPrompt: (expectedPrompt?: string) => void;
  setNewWorkspaceDialogPrefill: (prefill: NewWorkspaceDialogPrefill | null) => void;
  retainProvisioningWorkspacePrompt: (workspaceId: string, prompt: string) => void;
  settleProvisioningWorkspacePrompt: (
    workspace: Pick<Workspace, 'id' | 'provisioning' | 'provisionError'>
  ) => void;
}

export const useDialogsStore = create<DialogsState>((set) => ({
  newWorkspaceDialogPrompt: '',
  newWorkspaceDialogAttachments: [],
  newWorkspaceDialogPrefill: null,
  pendingWorkspacePrompts: {},

  setNewWorkspaceDialogPrompt: (prompt) => {
    set({ newWorkspaceDialogPrompt: prompt });
  },

  setNewWorkspaceDialogAttachments: (attachments) => {
    set({ newWorkspaceDialogAttachments: attachments });
  },

  clearNewWorkspaceDialogPrompt: (expectedPrompt) => {
    set((state) =>
      expectedPrompt === undefined || state.newWorkspaceDialogPrompt === expectedPrompt
        ? { newWorkspaceDialogPrompt: '' }
        : state
    );
  },

  setNewWorkspaceDialogPrefill: (prefill) => {
    set({ newWorkspaceDialogPrefill: prefill });
  },

  retainProvisioningWorkspacePrompt: (workspaceId, prompt) => {
    if (!prompt) return;
    set((state) => ({
      newWorkspaceDialogPrompt:
        state.newWorkspaceDialogPrompt === prompt ? '' : state.newWorkspaceDialogPrompt,
      pendingWorkspacePrompts: {
        ...state.pendingWorkspacePrompts,
        [workspaceId]: prompt,
      },
    }));
  },

  settleProvisioningWorkspacePrompt: (workspace) => {
    if (workspace.provisioning) return;
    set((state) => {
      const prompt = state.pendingWorkspacePrompts[workspace.id];
      if (!prompt) return state;

      const pendingWorkspacePrompts = { ...state.pendingWorkspacePrompts };
      delete pendingWorkspacePrompts[workspace.id];
      return {
        pendingWorkspacePrompts,
        newWorkspaceDialogPrompt:
          workspace.provisionError && !state.newWorkspaceDialogPrompt
            ? prompt
            : state.newWorkspaceDialogPrompt,
      };
    });
  },
}));

export const NEW_WORKSPACE_DIALOG_EVENT = 'open-new-workspace-dialog';

// Opens the new-workspace dialog from anywhere — App listens for this event.
// Optionally stages an initial prompt and/or prefill before opening.
export function openNewWorkspaceDialog(options?: {
  prompt?: string;
  prefill?: NewWorkspaceDialogPrefill;
}): void {
  if (options?.prompt) {
    useDialogsStore.getState().setNewWorkspaceDialogPrompt(options.prompt);
  }
  window.dispatchEvent(new CustomEvent(NEW_WORKSPACE_DIALOG_EVENT, { detail: options?.prefill }));
}
