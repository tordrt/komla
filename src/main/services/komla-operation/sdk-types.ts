import { z } from 'zod';

import { AGENT_CAPABILITIES } from '../../../shared/constants/agent-capabilities';
import { KOMLA_EVENT_LABELS, KOMLA_EVENT_TYPES } from '../../../shared/types/komla-events';

import { KOMLA_OPERATION_CAPABILITIES } from './capabilities';
import { komlaOperationResultSchemas } from './result-schema';
import { komlaOperationSchema } from './schema';

/**
 * Renders the Komla SDK's `src/generated.ts` from the schemas Komla validates operations with,
 * the result schemas and the capability table (ADR 0008). A test keeps the SDK's copy current;
 * `npm run generate:sdk` rewrites it.
 */

/** The subset of JSON Schema that Zod renders the operation schemas as. */
export interface JsonSchema {
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  additionalProperties?: boolean | JsonSchema;
  description?: string;
  minLength?: number;
  maxLength?: number;
  minimum?: number;
  maximum?: number;
  minItems?: number;
  maxItems?: number;
  pattern?: string;
}

const HEADER = `// Generated by \`npm run generate:sdk\` from the schemas Komla validates Komla Operations with
// (src/main/services/komla-operation/). Don't edit it by hand.
`;

function literal(value: unknown): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  return JSON.stringify(value);
}

function pascalCase(operationType: string): string {
  return operationType
    .split(/[.-]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function jsonSchema(schema: z.ZodType, io: 'input' | 'output'): JsonSchema {
  // A transform's output can't be rendered, and requests are typed as callers send them.
  return z.toJSONSchema(schema, { io, unrepresentable: 'any' }) as JsonSchema;
}

/** The limits a type can't carry, for its doc comment. */
function limits(schema: JsonSchema): string[] {
  const tags: string[] = [];
  if (schema.minLength !== undefined) tags.push(`@minLength ${schema.minLength}`);
  if (schema.maxLength !== undefined) tags.push(`@maxLength ${schema.maxLength}`);
  if (schema.minimum !== undefined) tags.push(`@minimum ${schema.minimum}`);
  if (schema.maximum !== undefined) tags.push(`@maximum ${schema.maximum}`);
  if (schema.minItems !== undefined) tags.push(`@minItems ${schema.minItems}`);
  if (schema.maxItems !== undefined) tags.push(`@maxItems ${schema.maxItems}`);
  if (schema.pattern !== undefined) tags.push(`@pattern ${schema.pattern}`);
  const items = schema.items ? limits(schema.items).map((tag) => tag.replace('@', '@items.')) : [];
  return [...tags, ...items];
}

function docComment(schema: JsonSchema, indent: string): string {
  // `*/` in a description or pattern would end the comment.
  const lines = [...(schema.description ? [schema.description] : []), ...limits(schema)].map(
    (line) => line.replace(/\*\//g, '*\\/')
  );
  if (lines.length === 0) return '';
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`).join('\n')}\n${indent} */\n`;
}

export function renderType(schema: JsonSchema, indent = ''): string {
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.enum) return schema.enum.map(literal).join(' | ');
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map((member) => renderType(member, indent)).join(' | ');
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => renderType({ ...schema, type }, indent)).join(' | ');
  }
  switch (schema.type) {
    case 'string':
    case 'boolean':
    case 'null':
      return schema.type;
    case 'number':
    case 'integer':
      return 'number';
    case 'array': {
      const items = renderType(schema.items ?? {}, indent);
      return /^[\w']+$/.test(items) ? `${items}[]` : `Array<${items}>`;
    }
    case 'object':
      return renderObject(schema, indent);
    default:
      return 'unknown';
  }
}

function renderObject(schema: JsonSchema, indent: string): string {
  const entries = Object.entries(schema.properties ?? {});
  // Requests and results are strict objects; a record or a loose object would need rendering of
  // its own, which a wrong type in its place would hide.
  if (schema.additionalProperties !== undefined && schema.additionalProperties !== false) {
    throw new Error('The SDK types render only strict objects, not records or loose objects.');
  }
  if (entries.length === 0) return 'Record<string, never>';
  const inner = `${indent}  `;
  const required = new Set(schema.required ?? []);
  const fields = entries.map(
    ([name, property]) =>
      `${docComment(property, inner)}${inner}${name}${required.has(name) ? '' : '?'}: ${renderType(property, inner)};`
  );
  return `{\n${fields.join('\n')}\n${indent}}`;
}

function renderInterface(name: string, schema: JsonSchema, description?: string): string {
  const doc = docComment({ description: description ?? schema.description }, '');
  return `${doc}export interface ${name} ${renderObject(schema, '')}\n`;
}

/** Each operation's request schema, one for each type even where two share a schema. */
function requestSchemas(): Array<{ type: string; schema: JsonSchema }> {
  const union = jsonSchema(komlaOperationSchema, 'input');
  return (union.oneOf ?? union.anyOf ?? []).flatMap((variant) => {
    const discriminator = variant.properties?.type;
    const types = discriminator?.enum ?? [discriminator?.const];
    return types.map((type) => ({
      type: String(type),
      schema: {
        ...variant,
        properties: { ...variant.properties, type: { type: 'string', const: type } },
      },
    }));
  });
}

export function renderKomlaSdkTypes(): string {
  const requests = requestSchemas();
  const types = requests.map((request) => request.type);
  const missing = Object.keys(komlaOperationResultSchemas).filter((type) => !types.includes(type));
  if (missing.length > 0) throw new Error(`No request schema for ${missing.join(', ')}.`);

  const capabilities = AGENT_CAPABILITIES.map(
    ({ id, description }) => `  { id: ${literal(id)}, description: ${literal(description)} },`
  );
  const requestInterfaces = requests.map(({ type, schema }) =>
    renderInterface(`${pascalCase(type)}Request`, schema)
  );
  const resultInterfaces = requests.map(({ type }) =>
    renderInterface(
      `${pascalCase(type)}Result`,
      jsonSchema(
        komlaOperationResultSchemas[type as keyof typeof komlaOperationResultSchemas],
        'output'
      ),
      `What \`${type}\` resolves to.`
    )
  );
  const operationCapabilities = requests.map(({ type }) => {
    const capability =
      KOMLA_OPERATION_CAPABILITIES[type as keyof typeof KOMLA_OPERATION_CAPABILITIES];
    const rendered =
      capability === null || typeof capability === 'string'
        ? literal(capability)
        : `{ by: ${literal(capability.by)}, capabilities: { ${Object.entries(
            capability.capabilities
          )
            .map(([value, id]) => `${value}: ${literal(id)}`)
            .join(', ')} } }`;
    return `  ${literal(type)}: ${rendered},`;
  });

  return [
    HEADER,
    '/** The capabilities a user can turn off for every adapter, and a client declares. */',
    'export const KOMLA_CAPABILITIES = [',
    ...capabilities,
    '] as const;',
    '',
    "export type KomlaCapability = (typeof KOMLA_CAPABILITIES)[number]['id'];",
    '',
    '/** Every Komla Operation, by its request `type`. */',
    'export const KOMLA_OPERATION_TYPES = [',
    ...types.map((type) => `  ${literal(type)},`),
    '] as const;',
    '',
    'export type KomlaOperationType = (typeof KOMLA_OPERATION_TYPES)[number];',
    '',
    requestInterfaces.join('\n'),
    'export type KomlaOperationRequest =',
    ...requests.map(
      ({ type }, index) =>
        `  | ${pascalCase(type)}Request${index === requests.length - 1 ? ';' : ''}`
    ),
    '',
    resultInterfaces.join('\n'),
    'export interface KomlaOperationResults {',
    ...requests.map(({ type }) => `  ${literal(type)}: ${pascalCase(type)}Result;`),
    '}',
    '',
    '/**',
    ' * The capability each operation needs, which Komla checks before it runs one: none, one, or one',
    ' * for each value of a request field.',
    ' */',
    'export const KOMLA_OPERATION_CAPABILITIES = {',
    ...operationCapabilities,
    '} as const;',
    '',
    '/**',
    ' * What happens in a workspace, which plugin code and panel pages follow with `komla.on`, and status',
    ' * items and sidebar panels name in `refreshOn`.',
    ' */',
    'export const KOMLA_EVENT_TYPES = [',
    ...KOMLA_EVENT_TYPES.map((type) => `  ${literal(type)},`),
    '] as const;',
    '',
    'export type KomlaEventType = (typeof KOMLA_EVENT_TYPES)[number];',
    '',
    '/** What each event is. */',
    'export const KOMLA_EVENT_LABELS: Record<KomlaEventType, string> = {',
    ...KOMLA_EVENT_TYPES.map((type) => `  ${literal(type)}: ${literal(KOMLA_EVENT_LABELS[type])},`),
    '};',
    '',
    '/** Something that happened in a workspace. */',
    'export interface KomlaEvent {',
    '  type: KomlaEventType;',
    '  workspaceId: string;',
    '  /** The terminal an agent event came from. */',
    '  terminalId?: string;',
    '  /** The agent an event came from, such as `claude-code`. */',
    '  agent?: string;',
    "  /** What the agent said, or the prompt sent to it. Plugin code gets it; panel pages don't. */",
    '  message?: string;',
    '}',
    '',
  ].join('\n');
}
